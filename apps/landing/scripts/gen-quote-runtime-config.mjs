// [#723] Inject the Supabase endpoint into the static quote page at build time.
//
// `public/quote/index.html` is a dependency-free vanilla-JS page that Vite copies
// verbatim, so it never sees `import.meta.env`. This script writes the one file it
// DOES read, `public/quote/runtime-config.js`, from the environment — the same
// `ALLY_OS_` prefix `vite.config.js` already declares in `envPrefix` and the same
// prefix `demoRole.js` reads for the portal and admin links (#977: not `VITE_`).
//
// FAIL-SOFT, DELIBERATELY, AND ONLY IN ONE DIRECTION. With no configuration this
// leaves the committed default in place — nulls — and the page stays inert with its
// disclosure intact. That is the documented unconfigured behaviour, not a failure,
// and it is what keeps a preview build from submitting into a real database.
//
// But a HALF-configured environment is a different thing and is treated as one: a
// URL with no key, or a key with no URL, is a deployment someone believed they had
// configured. Writing nulls there would silently swallow real enquiries exactly the
// way #723 describes, so it exits non-zero and says which half is missing.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const TARGET = join(HERE, '..', 'public', 'quote', 'runtime-config.js');

const url = (process.env.ALLY_OS_SUPABASE_URL ?? '').trim();
const key = (process.env.ALLY_OS_SUPABASE_ANON_KEY ?? '').trim();
// [FEAT-721 p6] The customer portal, for the prompt on the received screen.
//
// ⚠️ NOT part of the half-configured check below, deliberately. The two Supabase
// values are a PAIR — one without the other ships a form that looks live and
// records nothing, which is the defect #723 exists to close. This one is
// independent: absent, the received screen simply renders no portal prompt, and
// the submission it is celebrating still happened. Folding it into that check
// would make an unset portal address fail the whole build.
const portal = (process.env.ALLY_OS_PORTAL_URL ?? '').trim();

if ((url === '') !== (key === '')) {
  const missing = url === '' ? 'ALLY_OS_SUPABASE_URL' : 'ALLY_OS_SUPABASE_ANON_KEY';
  console.error(
    `gen-quote-runtime-config: ${missing} is empty while the other half is set. ` +
      'A half-configured build would ship a quote form that looks live and records ' +
      'nothing, which is the defect #723 exists to close. Set both, or neither.',
  );
  process.exit(1);
}

if (url === '') {
  console.log(
    'gen-quote-runtime-config: no ALLY_OS_SUPABASE_* in the environment — leaving ' +
      'the committed unconfigured default in place (quote page stays inert and ' +
      'discloses it).',
  );
  process.exit(0);
}

// One `new URL` guard, mirroring configuredAppBase() in demoRole.js: a malformed
// endpoint must fail the build, not become a string the page tries to fetch.
let origin;
try {
  const parsed = new URL(url);
  if (parsed.protocol !== 'https:' && parsed.protocol !== 'http:') {
    throw new Error(`unsupported protocol ${parsed.protocol}`);
  }
  origin = `${parsed.origin}${parsed.pathname}`.replace(/\/+$/, '');
} catch (err) {
  console.error(`gen-quote-runtime-config: ALLY_OS_SUPABASE_URL is not a usable URL — ${err.message}`);
  process.exit(1);
}

// [FEAT-721 p6] Same URL guard as the endpoint above, and the same reason: this
// value is written into an href on the received screen, so a malformed or a
// non-http string must not reach the page. Unlike the endpoint it does NOT fail
// the build — an unset portal simply means no prompt is rendered.
let portalOrigin = null;
if (portal !== '') {
  try {
    const parsedPortal = new URL(portal);
    if (parsedPortal.protocol !== 'https:' && parsedPortal.protocol !== 'http:') {
      throw new Error(`unsupported protocol ${parsedPortal.protocol}`);
    }
    portalOrigin = `${parsedPortal.origin}${parsedPortal.pathname}`.replace(/\/+$/, '');
  } catch (err) {
    console.error(`gen-quote-runtime-config: ALLY_OS_PORTAL_URL is not a usable URL — ${err.message}`);
    process.exit(1);
  }
}

writeFileSync(
  TARGET,
  `// GENERATED by scripts/gen-quote-runtime-config.mjs during build — do not edit.\n` +
    `// The committed version of this file carries nulls; see it for why the page\n` +
    `// reads configuration at runtime at all.\n` +
    `window.__ALLY_OS_CONFIG__ = ${JSON.stringify({ supabaseUrl: origin, anonKey: key, portalUrl: portalOrigin }, null, 2)};\n`,
  'utf8',
);

console.log(`gen-quote-runtime-config: quote page pointed at ${origin}`);
